  id_categoria_menu bigint generated by default as identity primary key,
  nombre_categoria text not null unique,
  codigo text not null unique,
  created_at timestamptz default now(),
  created_by uuid,
  updated_at timestamptz default now(),
  updated_by uuid
);

create table if not exists public.alimentos (
  id_alimento bigint generated by default as identity primary key,
  id_categoria_menu bigint references public.categorias_menu(id_categoria_menu) on delete cascade,
  nombre_alimento text not null,
  nombre_normalizado text generated always as (
    lower(regexp_replace(btrim(nombre_alimento), '\s+', ' ', 'g'))
  ) stored,
  created_at timestamptz default now(),
  created_by uuid,
  updated_at timestamptz default now(),
  updated_by uuid,
  unique (id_categoria_menu, nombre_alimento),
  unique (id_categoria_menu, nombre_normalizado)
);

create table if not exists public.telegram_bot_state (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

drop trigger if exists update_telegram_bot_state_updated_at on public.telegram_bot_state;
create trigger update_telegram_bot_state_updated_at
before update on public.telegram_bot_state
for each row execute function public.update_telegram_bot_state_updated_at();

