create or replace function public.update_telegram_bot_state_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.rls_auto_enable()
returns event_trigger
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  command record;
begin
  for command in
    select *
    from pg_event_trigger_ddl_commands()
    where command_tag in ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      and object_type in ('table', 'partitioned table')
  loop
    if command.schema_name = 'public' then
      begin
        execute format('alter table if exists %s enable row level security', command.object_identity);
      exception when others then
        raise log 'rls_auto_enable failed for %', command.object_identity;
      end;
    end if;
  end loop;
end;
$$;

do $$
begin
  if not exists (select 1 from pg_event_trigger where evtname = 'ensure_rls') then
    execute $event_trigger$
      create event trigger ensure_rls
        on ddl_command_end
        when tag in ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
        execute function public.rls_auto_enable()
    $event_trigger$;
  end if;
end;
$$;

create table if not exists public.roles (
  id_rol bigint generated by default as identity primary key,
  nombre_rol text not null unique,
  created_at timestamptz default now(),
  created_by uuid,
  updated_at timestamptz default now(),
  updated_by uuid
);

create table if not exists public.empleados (
  id uuid primary key references auth.users(id) on delete cascade,
  id_rol bigint references public.roles(id_rol),
  nombre text not null,
  apellido text not null,
  nombre_usuario text not null unique,
  correo text unique,
  esta_activo boolean default true,
  created_at timestamptz default now(),
  created_by uuid,
  updated_at timestamptz default now(),
  updated_by uuid
);

create table if not exists public.categorias_productos (
  id_categoria bigint generated by default as identity primary key,
  nombre_categoria text not null unique,
  created_at timestamptz default now(),
  created_by uuid
);

create table if not exists public.productos (
  id_producto bigint generated by default as identity primary key,
  id_categoria bigint references public.categorias_productos(id_categoria),
  nombre_producto text not null unique,
  precio_unitario numeric(10,2) not null,
  descripcion text,
  esta_activo boolean default true,
  created_at timestamptz default now(),
  created_by uuid,
  updated_at timestamptz default now(),
  updated_by uuid
);

create table if not exists public.tipos_cliente (
  id_tipo_cliente bigint generated by default as identity primary key,
  nombre_tipo text not null unique
);

create table if not exists public.convenios (
  id_convenio uuid primary key default gen_random_uuid(),
  ruc text not null unique,
  nombre_empresa text not null,
  representante text,
  telefono text,
  email text,
  fecha_inicio date not null,
  fecha_caducidad date not null,
  esta_activo boolean default true,
  cupo_maximo integer default 0,
  archivo_firmado text,
  created_at timestamptz default now(),
  created_by uuid,
  updated_at timestamptz default now(),
  updated_by uuid
);

create table if not exists public.clientes (
  id_cliente uuid primary key default gen_random_uuid(),
  id_tipo_cliente bigint references public.tipos_cliente(id_tipo_cliente),
  cedula text not null unique,
  nombre text not null,
  apellido text not null,
  telefono text,
  esta_activo boolean default true,
  created_at timestamptz default now(),
  created_by uuid,
  updated_at timestamptz default now(),
  updated_by uuid
);

create table if not exists public.clientes_convenios (
  id_cliente uuid not null references public.clientes(id_cliente) on delete cascade,
  id_convenio uuid not null references public.convenios(id_convenio) on delete cascade,
  created_at timestamptz default now(),
  created_by uuid,
  primary key (id_cliente, id_convenio)
